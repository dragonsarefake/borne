#!/usr/bin/env python3
"""Turns the USB button board into logical game events.

The board's own labels (K1..K12) never appear above this file. The game asks for
L1..L5 / R1..R5 / START / SELECT, and mapping.json says which physical key that
is - generated by scan.py, so nothing is hard-coded to one board.
"""

import json
import os
import threading

try:
    from evdev import InputDevice, ecodes, list_devices
except ImportError:
    raise SystemExit("python-evdev is missing.  pip install evdev")

HERE = os.path.dirname(os.path.abspath(__file__))
MAPPING_PATH = os.path.join(HERE, "mapping.json")

# Ten buttons: five rows of two, a left and a right at each row height. Defined
# here so scan.py, rowcal.py and the game all agree without duplicating them.
LOGICAL_BUTTONS = [f"L{i}" for i in range(1, 6)] + [f"R{i}" for i in range(1, 6)]
EXTRA_BUTTONS = ["START", "SELECT"]

UP, DOWN, REPEAT = 0, 1, 2


def _key_name(code):
    name = ecodes.bytype[ecodes.EV_KEY].get(code, str(code))
    return name[0] if isinstance(name, (list, tuple)) else name


class Buttons:
    """Reads the board in a background thread and calls your handlers.

        on_press(logical, host_time)
        on_release(logical, host_time)

    host_time comes from the KERNEL's event timestamp, so it is accurate even if
    Python was busy elsewhere - which matters for a quicktime game.
    """

    def __init__(self, path=None, mapping_path=MAPPING_PATH, grab=True):
        self.mapping = self._load_mapping(mapping_path)
        self.device = InputDevice(path) if path else self._autodetect(mapping_path)
        self.on_press = None
        self.on_release = None
        self.held = set()

        # Grabbing stops the presses also reaching the desktop as keystrokes.
        # Without it, a board emulating a keyboard types into whatever has focus.
        self.grabbed = False
        if grab:
            try:
                self.device.grab()
                self.grabbed = True
            except OSError:
                pass   # already grabbed, or insufficient privilege

        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._loop, daemon=True)
        self._thread.start()

    @staticmethod
    def _load_mapping(path):
        if not os.path.exists(path):
            raise SystemExit(
                f"No {path}. Run:  ./scan.py map\n"
                "Nothing assumes a layout - the mapping has to be generated once.")
        with open(path) as fh:
            return json.load(fh)

    def _autodetect(self, mapping_path):
        want = self.mapping.get("device_name")
        for p in sorted(list_devices()):
            try:
                dev = InputDevice(p)
            except PermissionError:
                continue
            if want and dev.name == want:
                return dev
        raise SystemExit(
            f"Could not find the device named {want!r} from {mapping_path}.\n"
            "Plug the board in, or re-run ./scan.py map if it changed.")

    def close(self):
        self._stop.set()
        if self.grabbed:
            try:
                self.device.ungrab()
            except OSError:
                pass

    def _loop(self):
        keys = self.mapping["buttons"]
        for event in self.device.read_loop():
            if self._stop.is_set():
                return
            if event.type != ecodes.EV_KEY:
                continue
            # value 2 is kernel autorepeat on keyboard-style devices. A held
            # button is not a new press, so it never becomes a game event.
            if event.value == REPEAT:
                continue
            logical = keys.get(_key_name(event.code))
            if logical is None:
                continue
            when = event.timestamp()
            if event.value == DOWN:
                self.held.add(logical)
                if self.on_press:
                    self.on_press(logical, when)
            elif event.value == UP:
                self.held.discard(logical)
                if self.on_release:
                    self.on_release(logical, when)
