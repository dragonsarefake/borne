#!/usr/bin/env python3
"""Build install_pad.sh from pad.py, so the installer never carries a stale copy.

    python make_installer.py

Run it again whenever pad.py changes.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

HEAD = r"""# Force pad -> USB joystick, installed on the Pi from its own terminal.
# Nothing to plug in and no SD card to pull: the Pi only needs internet, for
# two apt packages. Either
#     - paste this WHOLE file into the Pi's terminal, or
#     - copy it over and run:  bash install_pad.sh
# Safe to run again; it replaces what it installed last time.
# GENERATED by make_installer.py from pad.py - edit pad.py, not this file.
sudo bash -s <<'INSTALL_PAD'
set -e
echo "== packages (needs internet)"
apt-get update -qq
apt-get install -y python3-serial python3-evdev

echo "== uinput, now and at every boot"
modprobe uinput
echo uinput > /etc/modules-load.d/uinput.conf

echo "== /opt/pad/pad.py"
mkdir -p /opt/pad
cat > /opt/pad/pad.py <<'PAD_PY'
"""

TAIL = r"""PAD_PY
chmod +x /opt/pad/pad.py

echo "== service, started now and at every boot"
cat > /etc/systemd/system/pad.service <<'UNIT'
[Unit]
Description=Force pad: USB serial to joystick
After=systemd-modules-load.service

[Service]
ExecStart=/usr/bin/python3 /opt/pad/pad.py
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
UNIT

echo "== self-update: a minute after boot, then hourly"
# Fetches pad.py from GitHub. It is swapped in ONLY if it differs from what
# is running and it compiles, and the bridge is restarted only then - so with
# no internet, or nothing new, this does nothing at all. The joystick never
# waits for the network: the bridge starts on its own, this runs beside it.
cat > /opt/pad/update.sh <<'UPDATE_SH'
#!/bin/sh
URL=https://raw.githubusercontent.com/dragonsarefake/borne/main/pi/pad.py
cd /opt/pad || exit 0
curl -fsSL --max-time 20 "$URL" -o pad.py.new || { rm -f pad.py.new; exit 0; }
if cmp -s pad.py.new pad.py; then rm -f pad.py.new; exit 0; fi
if python3 -m py_compile pad.py.new && grep -q 'def make_joystick' pad.py.new; then
  cp pad.py pad.py.old
  mv pad.py.new pad.py
  systemctl restart pad.service
  echo "pad.py updated (previous kept as pad.py.old)"
else
  rm -f pad.py.new
  echo "downloaded pad.py does not compile - kept the one that works"
fi
UPDATE_SH
chmod +x /opt/pad/update.sh
cat > /etc/systemd/system/pad-update.service <<'UNIT'
[Unit]
Description=Force pad: fetch a newer pad.py if there is one

[Service]
Type=oneshot
ExecStart=/opt/pad/update.sh
UNIT
cat > /etc/systemd/system/pad-update.timer <<'UNIT'
[Unit]
Description=Force pad: check for updates

[Timer]
OnBootSec=1min
OnUnitActiveSec=1h

[Install]
WantedBy=timers.target
UNIT

systemctl daemon-reload
systemctl enable pad.service
systemctl restart pad.service
systemctl enable --now pad-update.timer
sleep 3

echo
echo "== result"
systemctl --no-pager --lines=5 status pad.service || true
echo
if grep -q 'esp32borne' /proc/bus/input/devices; then
  echo "OK: the joystick exists:"
  grep -A4 'esp32borne' /proc/bus/input/devices | grep -E 'Name|Handlers'
else
  echo "PROBLEM: no joystick was created. Look at:  journalctl -u pad -n 30"
fi
if ls /dev/ttyUSB* /dev/ttyACM* >/dev/null 2>&1; then
  echo "OK: a USB serial port is present: $(ls /dev/ttyUSB* /dev/ttyACM* 2>/dev/null | tr '\n' ' ')"
else
  echo "NOTE: no /dev/ttyUSB* yet - the pad is not plugged into the Pi."
  echo "      The joystick is there anyway and comes alive when it is."
fi
if dpkg -s brltty >/dev/null 2>&1; then
  echo "NOTE: 'brltty' is installed and is known to grab this USB serial chip."
  echo "      If the port keeps vanishing:  sudo apt remove brltty"
fi
INSTALL_PAD
"""

with open(os.path.join(HERE, "pad.py"), encoding="utf-8") as f:
    pad = f.read()
for marker in ("PAD_PY", "INSTALL_PAD", "UPDATE_SH", "UNIT\n"):
    if marker in pad:
        raise SystemExit("pad.py contains the heredoc marker %r" % marker)
if not pad.endswith("\n"):
    pad += "\n"

out = os.path.join(HERE, "install_pad.sh")
with open(out, "w", encoding="utf-8", newline="\n") as f:   # LF: this runs on Linux
    f.write(HEAD + pad + TAIL)
print("wrote %s (%d bytes)" % (out, os.path.getsize(out)))
